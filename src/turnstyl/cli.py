@app.command("ledger")
def ledger(buyer: str = typer.Argument(..., help="Buyer wallet address.")) -> None:
    """Print what memory knows about one buyer."""
    engine = build_engine()
    data = engine.ledger(buyer)
    render_reconciled(data.get("reconciled", []))
    book = data["ledger"]
    if not data["known"]:
        console.print(
            Text(
                f"No ledger for {data['buyer']} in {engine.store.db_path}. "
                f"This buyer is unknown to memory.",
                style="yellow",
            )
        )
        return

    grid = Table.grid(padding=(0, 2))
    grid.add_column(style="dim", justify="right")
    grid.add_column()
    grid.add_row("buyer", data["buyer"])
    grid.add_row("paid steps", str(book.paid_steps))
    grid.add_row("paid", f"{book.paid_usdc:.2f} USDC")
    grid.add_row("open invoices", str(book.open_invoices))
    grid.add_row("unpaid from prior jobs", str(book.unpaid_from_prior_jobs))
    grid.add_row("defaults on record", str(book.defaults))
    grid.add_row("completed paid jobs", str(book.completed_paid_jobs))
    if book.defaults:
        grid.add_row(
            "clean paid steps since",
            f"{book.consecutive_paid_since_default} "
            f"(credit returns at {S.EARN_BACK_PAID_STEPS})",
        )
    grid.add_row("trust tier", book.trust_tier)
    grid.add_row("jobs", str(len(book.jobs)))
    console.print(Panel(grid, title="LEDGER", border_style="cyan", padding=(1, 2)))

    job_types = {j["job_id"]: j.get("job_type") for j in data["jobs"]}
    if book.outstanding:
        table = Table(title="OUTSTANDING", border_style="yellow")
        table.add_column("job")
        table.add_column("step")
        table.add_column("amount USDC", justify="right")
        for item in book.outstanding:
            table.add_row(
                item.job_id,
                f"{item.step} ({jobtypes.get(job_types.get(item.job_id)).step_name(item.step)})",
                f"{item.amount_usdc:.2f}",
            )
        console.print(table)

    if data["jobs"]:
        table = Table(title="JOBS", border_style="cyan")
        table.add_column("job")
        table.add_column("status")
        table.add_column("step", justify="right")
        table.add_column("steps recorded")
        table.add_column("contract")
        for job in data["jobs"]:
            table.add_row(
                job["job_id"],
                job["status"],
                str(job["current_step"]),
                ",".join(job["steps_recorded"]) or ("archived" if job["archived"] else "-"),
                job["contract_hash"][:12],
            )
        console.print(table)
    console.print(Text(f"memory read: {', '.join(data['memory_read'])}", style="dim"))


@app.command("worker")
def worker(
    db: str = typer.Option(
        None, "--db", help="Database to watch. Defaults to $TURNSTYL_DB."
    ),
    interval: float = typer.Option(3.0, "--interval", help="Seconds between passes."),
    once: bool = typer.Option(False, "--once", help="One pass, then exit."),
) -> None:
    """Run active jobs automatically as their invoices are settled.

    Every pass reconciles each buyer and runs the current step of any job the
    policy would run, through the same engine as `job run`. Waiting jobs are
    looked at but not written about. Ctrl-C stops it cleanly.
    """
    from .worker import main as worker_main

    if db:
        os.environ[DB_PATH_ENV_VAR_MEMORY] = db
    announce_memory()
    raise typer.Exit(code=worker_main(None, interval, once))


def announce_memory() -> None:
    """Create the store if it is absent and say which one is in use.

    Startup is the only moment turnstyl creates a database on purpose. The
    API and the worker loop refuse to recreate one that disappears while they
    run, so the delete beat stays a real loss.
    """
    from .memory import bootstrap_memory

    try:
        path, created, records = bootstrap_memory()
    except Exception as e:  # surfaced with the path so an operator can act
        fail(f"turnstyl: could not open or create the memory file: {type(e).__name__}: {e}")
        raise
    # soft_wrap: these lines are grepped from logs, and Rich would otherwise
    # fold a long path onto a second line when stdout is not a terminal.
    if created:
        console.print(Text(f"memory: created {path}", style="dim"), soft_wrap=True)
    else:
        console.print(Text(f"memory: using {path} ({records} records)", style="dim"), soft_wrap=True)


@app.command("serve")
def serve(
    host: str = typer.Option("127.0.0.1", "--host", help="Interface to bind."),
    port: int = typer.Option(8787, "--port", help="Port to listen on."),
    db: str = typer.Option(
        None, "--db", help="Database to read. Defaults to $TURNSTYL_DB."
    ),
    with_worker: bool = typer.Option(
        False, "--with-worker", help="Also run the worker loop in this process."
    ),
    interval: float = typer.Option(
        3.0, "--interval", help="Worker pass interval in seconds (with --with-worker)."
    ),
) -> None:
    """Serve the web view of this agent's memory.

    Binds 127.0.0.1 unless --host says otherwise. GET endpoints never write; POST /api/jobs hands a
    contract to the engine exactly as `job new` does. With --with-worker the
    worker loop runs in a background thread of the same process, so the demo
    is one command.
    """
    import uvicorn

    if db:
        # api.py resolves the path per request, so setting it here is enough.
        os.environ[DB_PATH_ENV_VAR_MEMORY] = db

    # Bind-check first: uvicorn reports "address already in use" only after we
    # would have printed a URL that serves someone else's process.
    import socket

    probe = socket.socket(socket.AF_INET, socket.SOCK_STREAM)
    probe.setsockopt(socket.SOL_SOCKET, socket.SO_REUSEADDR, 1)
    try:
        probe.bind((host, port))
    except OSError as e:
        probe.close()
        fail(
            f"turnstyl: cannot serve on {host}:{port}: {e}.\n"
            f"  Something is already listening there. Find it with "
            f"'lsof -nP -iTCP:{port} -sTCP:LISTEN', or pass a different --port."
        )
        raise
    probe.close()

    console.print(
        Text(f"turnstyl serving http://{host}:{port}", style="bold"), soft_wrap=True
    )
    announce_memory()
    if with_worker:
        from .worker import start_in_thread

        start_in_thread(None, interval)
    uvicorn.run("turnstyl.api:app", host=host, port=port, log_level="warning")


@app.command("reset")
def reset(
    db: str = typer.Option(..., "--db", help="Path to the turnstyl database to delete."),
) -> None:
    """Delete a turnstyl memory store. This is the delete test.

    Reports what the store held before removing it, so what is being destroyed
    is on the record. Refuses any path outside ./data/.
    """
    import sqlite3

    target = Path(db).expanduser()
    data_dir = (PROJECT_ROOT / "data").resolve()
    try:
        resolved = target.resolve()
    except OSError as e:
        fail(f"turnstyl: cannot resolve {target}: {e}")
        raise
    if resolved.parent != data_dir:
        fail(
            f"turnstyl: refusing to delete {resolved}.\n"
            f"  reset only removes databases directly inside {data_dir}."
        )
    if not resolved.is_file():
        fail(
            f"turnstyl: no database at {resolved}. Nothing to delete.\n"
            f"  Run '.venv/bin/turnstyl status' to see which store is in use."
        )

    size = resolved.stat().st_size
    # Counted with sqlite3 rather than the SDK: there is no public API that
    # lists state keys, and this has to read all three tables before the file
    # stops existing.
    try:
        conn = sqlite3.connect(f"file:{resolved}?mode=ro", uri=True)
        count = lambda sql: conn.execute(sql).fetchone()[0]  # noqa: E731
        states = count("SELECT count(*) FROM state_documents")
        entities = count("SELECT count(*) FROM entities")
        archived = count("SELECT count(*) FROM archived_entities")
        events = count("SELECT count(*) FROM journal_events")
        conn.close()
    except sqlite3.Error as e:
        fail(
            f"turnstyl: {resolved} is not a readable turnstyl database ({e}).\n"
            f"  Refusing to delete a file this command cannot account for."
        )
        raise

    grid = Table.grid(padding=(0, 2))
    grid.add_column(style="dim", justify="right")
    grid.add_column()
    grid.add_row("database", str(resolved))
    grid.add_row("size", f"{size:,} bytes")
    grid.add_row("state keys", str(states))
    grid.add_row("entities", f"{entities} live, {archived} archived")
    grid.add_row("journal events", str(events))
    console.print(
        Panel(
            grid,
            title="ABOUT TO DELETE",
            border_style="red",
            padding=(1, 2),
            width=panel_width(),
        )
    )

    removed = []
    for suffix in ("", "-wal", "-shm"):
        sidecar = Path(str(resolved) + suffix)
        if sidecar.exists():
            sidecar.unlink()
            removed.append(sidecar.name)
    if resolved.exists():
        fail(f"turnstyl: failed to delete {resolved}; it is still on disk.")

    console.print(
        Text(
            f"memory deleted: {resolved} ({entities} entities, {events} "
            f"journal events gone)",
            style="bold red",
        )
    )


@app.command("status")
def status() -> None:
    """List the active jobs held in memory."""
    engine = build_engine()
    data = engine.status()
    if not data["active_jobs"]:
        console.print(
            Text(f"No active jobs in {data['db_path']}.", style="yellow")
        )
        return
    table = Table(title="ACTIVE JOBS", border_style="cyan")
    table.add_column("job")
    table.add_column("buyer")
    table.add_column("status")
    table.add_column("step", justify="right")
    table.add_column("open invoice")
    table.add_column("contract")
    for state in data["active_jobs"]:
        invoice = state.open_invoice
        table.add_row(
            state.job_id,
            state.buyer,
            state.status,
            f"{state.current_step}/{jobtypes.get(state.job_type).last_step}",
            f"{invoice.amount_usdc:.2f} USDC step {invoice.step}" if invoice else "-",
            state.contract_hash[:12],
        )
    console.print(table)
    if data["orphans"]:
        console.print(
            Text(
                f"warning: {len(data['orphans'])} active job id(s) have no state "
                f"document: {', '.join(data['orphans'])}",
                style="red",
            )
        )
    console.print(Text(f"memory read: {', '.join(data['memory_read'])}", style="dim"))


