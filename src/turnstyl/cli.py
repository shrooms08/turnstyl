DECISION_STYLE = {
    S.RUN_FREE: "cyan",
    S.RUN_PAID: "green",
    S.RUN_ON_CREDIT: "yellow",
    S.WAIT_FOR_PAYMENT: "magenta",
    S.REFUSE: "red",
    "RESUME_EXISTING": "cyan",
    "SKIP_ALREADY_DONE": "cyan",
    "ALREADY_COMPLETE": "cyan",
}


def agent_address() -> str:
    """The address a buyer pays. Public by definition; no secret is ever read."""
    return os.environ.get("AGENT_ADDRESS") or "(AGENT_ADDRESS not set in .env)"


def render_memory_read(outcome: Outcome) -> None:
    if outcome.memory_read:
        console.print(
            Text(f"memory read: {', '.join(outcome.memory_read)}", style="dim")
        )


def render_decision(outcome: Outcome) -> None:
    """The verdict: one plain sentence, the DECISION line for the camera, then
    the full reason in dim text below it."""
    if not outcome.decision:
        return
    if outcome.summary:
        console.print(Text(outcome.summary))
    style = DECISION_STYLE.get(outcome.decision, "white")
    line = Text("DECISION: ", style="bold")
    line.append(outcome.decision, style=f"bold {style}")
    console.print(line)
    if outcome.reason:
        console.print(Text(f"because {outcome.reason}", style="dim"))


def render_step(outcome: Outcome) -> None:
    if outcome.output is None or outcome.step is None:
        return
    served = "from memory (cached)" if outcome.cached else "from the model"
    subtitle = (
        f"{served} | {outcome.tokens} tokens | {outcome.seconds:.2f}s | "
        f"{outcome.price_usdc:.2f} USDC | sha256 {S.sha256_text(outcome.output)[:12]}"
    )
    if outcome.tests_total is not None:
        # A suite that runs is the gate; failing tests may be documenting real
        # defects, so the counts go in the panel rather than a pass/fail verdict.
        subtitle += (
            f" | TESTS: {outcome.tests_passed} passed, {outcome.tests_failed} failed"
        )
    elif outcome.compiles is not None:
        # The gated step's mechanical verdict belongs with the step's other facts,
        # inside the panel it describes. The diff is generated by turnstyl so it
        # always applies; whether it compiles is the real question.
        label = "TESTS COMPILE" if outcome.step_name == "tests" else "PATCH COMPILES"
        subtitle += f" | {label}: {'yes' if outcome.compiles else 'no'}"
    console.print(
        Panel(
            # Text(), not a bare str: step output is Solidity, and rich would
            # read `balances[msg.sender]` as console markup and eat the index.
            Text(outcome.output),
            title=f"STEP {outcome.step}: {outcome.step_name or outcome.step}",
            subtitle=subtitle,
            border_style="cyan",
            padding=(1, 2),
            width=panel_width(),
        )
    )


def render_invoice(
    invoice: S.OpenInvoice | None,
    price_reason: str = "",
    engine: Engine | None = None,
    job_id: str | None = None,
    job_type: str | None = None,
) -> None:
    if invoice is None:
        return
    spec = jobtypes.get(job_type)
    backend = engine.payments if engine is not None else None
    payee = backend.payee_address() if backend else agent_address()
    reason = price_reason or invoice.price_reason
    body = Table.grid(padding=(0, 2))
    body.add_column(style="dim", justify="right")
    body.add_column()
    body.add_row("step", f"{invoice.step} ({spec.step_name(invoice.step)})")
    body.add_row("amount", f"{invoice.amount_usdc:.2f} USDC")
    body.add_row("pay to", payee)
    body.add_row("memo", invoice.memo)
    body.add_row("status", "settled" if invoice.paid else "unpaid")
    if reason:
        body.add_row("priced", Text(reason))
    if backend is not None and job_id:
        body.add_row("buyer runs", backend.buyer_command(job_id, invoice.step))
    console.print(
        Panel(
            body,
            title="INVOICE",
            border_style="yellow",
            padding=(1, 2),
            width=panel_width(),
        )
    )


def render_commit(outcome: Outcome) -> None:
    """The receipt for what was just delivered."""
    if outcome.commit_tx and outcome.commit_hash:
        line = Text("COMMITTED ", style="bold green")
        line.append(outcome.commit_hash[:10])
        line.append(" tx ")
        line.append(outcome.commit_tx)
        console.print(line)
        console.print(Text(explorer_tx(outcome.commit_tx), style="dim"))
    elif outcome.commit_error:
        console.print(
            Text(
                f"WARNING: on-chain commit failed and was skipped: "
                f"{outcome.commit_error}",
                style="bold yellow",
            )
        )
        console.print(
            Text(
                "The step output is recorded in memory; only its on-chain receipt "
                "is missing.",
                style="dim",
            )
        )


def render_reconciled(outcome_or_list) -> None:
    items = (
        outcome_or_list
        if isinstance(outcome_or_list, list)
        else outcome_or_list.reconciled
    )
    for item in items:
        line = Text("RECONCILED ", style="bold green")
        line.append(
            f"step {item['step']} of job {item['job_id']} "
            f"({item['amount_usdc']:.2f} USDC) settled on chain"
        )
        console.print(line)
        console.print(Text(explorer_tx(item["tx_hash"]), style="dim"))


def render_injection(outcome: Outcome, engine: Engine | None = None) -> None:
    """Say it before anything else if the source tried to instruct the auditor."""
    if engine is None or not outcome.job_id:
        return
    state = engine.store.get_job_state(outcome.job_id)
    flags = list(state.injection_flags) if state else []
    if not flags:
        return
    lines = [
        "This contract contains text that tries to instruct the auditor. Found "
        "by a mechanical scan of its comments and strings before any model saw "
        "it, recorded on the job, and handed to the audit as evidence.",
        "",
    ]
    for flag in flags[:8]:
        lines.append(f"line {flag.line:>4}  {flag.rule:<20} {flag.matched or flag.text[:70]}")
    if len(flags) > 8:
        lines.append(f"... and {len(flags) - 8} more")
    console.print(
        Panel(
            "\n".join(lines),
            title=f"UNTRUSTED SOURCE: {len(flags)} flagged passage(s)",
            border_style="red",
            padding=(1, 2),
            width=panel_width(),
        )
    )


def render_outcome(outcome: Outcome, engine: Engine | None = None) -> None:
    render_reconciled(outcome)
    render_injection(outcome, engine)
    for hint in outcome.memory_hints:
        console.print(Text(f"memory hint: {hint}", style="dim"))
    render_step(outcome)
    render_commit(outcome)
    render_invoice(
        outcome.invoice, outcome.price_reason, engine, outcome.job_id, outcome.job_type
    )
    if outcome.complete:
        console.print(
            Panel(
                f"Job {outcome.job_id} is complete. All "
                f"{jobtypes.get(outcome.job_type).last_step} outputs are cached in "
                f"memory under {outcome.job_type} for this contract hash; a repeat "
                f"{outcome.job_type} job on the same contract is served from memory "
                f"at half price.",
                title="COMPLETE",
                border_style="green",
                padding=(1, 2),
            )
        )
    elif outcome.note:
        console.print(Text(outcome.note, style="dim"))
    # Last two lines on screen: what memory said, then the verdict it produced.
    render_memory_read(outcome)
    render_decision(outcome)


def fail(message: str) -> None:
    err_console.print(Text(message, style="bold red"))
    raise typer.Exit(code=1)


def build_engine() -> Engine:
    try:
        return Engine()
    except Exception as e:  # surfaced with the path so an operator can act
        fail(f"turnstyl: could not start the engine: {type(e).__name__}: {e}")
        raise


@app.command("types")
def types() -> None:
    """List the services on offer, with their steps and prices."""
    for spec in jobtypes.all_types():
        grid = Table.grid(padding=(0, 2))
        grid.add_column(style="dim", justify="right")
        grid.add_column()
        for step in spec.steps:
            gate = "" if step.gate == "none" else f"  [{step.gate} gate]"
            grid.add_row(
                f"step {step.n}",
                f"{step.name:<10} {step.base_price_usdc:.2f} USDC{gate}",
            )
        grid.add_row("total", f"{sum(s.base_price_usdc for s in spec.steps):.2f} USDC")
        grid.add_row("run", f"turnstyl job new <file> --buyer <addr> --type {spec.id}")
        console.print(
            Panel(
                grid,
                title=f"{spec.id}  ({spec.name})",
                subtitle=spec.description,
                border_style="cyan",
                padding=(1, 2),
                width=panel_width(),
            )
        )


@job_app.command("new")
def job_new(
    contract: str = typer.Argument(..., help="Path to the Solidity contract."),
    buyer: str = typer.Option(..., "--buyer", help="Buyer wallet address."),
    job_type: str = typer.Option(
        jobtypes.DEFAULT_TYPE_ID, "--type", help="Service id; see 'turnstyl types'."
    ),
) -> None:
    """Start a job, or resume the open one for this contract and service."""
    engine = build_engine()
    try:
        outcome = engine.new_job(contract, buyer, job_type)
    except Exception as e:
        fail(f"turnstyl: {e}")
        raise
    console.print(
        Text(
            f"job {outcome.job_id}  type {outcome.job_type}  "
            f"buyer {engine.store.buyer_key(buyer)}",
            style="dim",
        )
    )
    render_outcome(outcome, engine)


@job_app.command("run")
def job_run(job_id: str = typer.Argument(..., help="Job id from 'job new'.")) -> None:
    """Run the current step of a job."""
    engine = build_engine()
    try:
        outcome = engine.run(job_id)
    except Exception as e:
        fail(f"turnstyl: {e}")
        raise
    console.print(
        Text(
            f"job {outcome.job_id}  type {outcome.job_type}  "
            f"status {outcome.status}",
            style="dim",
        )
    )
    render_outcome(outcome, engine)


